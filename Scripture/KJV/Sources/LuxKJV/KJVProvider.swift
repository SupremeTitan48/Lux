import Foundation
import LuxCore

/// The King James Version, bundled with this package and verified against
/// its manifest when loaded.
///
/// Books are decoded the first time a passage needs them. Book names are the
/// canonical names of Lux's lectionaries (`Ecclesiasticus`, `Song of
/// Solomon`, `1 Kings`).
public final class KJVProvider: ScriptureProvider, @unchecked Sendable {
    public static let identifier = "kjv"

    public let translationID = KJVProvider.identifier
    public let title = "King James Version"
    public let manifest: ContentManifest
    public let index: KJVIndex

    private let directory: URL
    private let lock = NSLock()
    private var books: [String: KJVBook] = [:]

    public enum LoadError: Error {
        case resourcesMissing
    }

    public static func bundled(verify: Bool = true) throws -> KJVProvider {
        guard let root = Bundle.module.url(forResource: "Content", withExtension: nil) else {
            throw LoadError.resourcesMissing
        }
        return try KJVProvider(directory: root, verify: verify)
    }

    public init(directory: URL, verify: Bool = true) throws {
        self.directory = directory
        manifest = try JSONDecoder().decode(ContentManifest.self, from: Data(contentsOf: directory.appendingPathComponent("manifest.json")))
        if verify { try manifest.verify(in: directory) }
        index = try JSONDecoder().decode(KJVIndex.self, from: Data(contentsOf: directory.appendingPathComponent("index.json")))
    }

    public var sourceID: String { manifest.source.id }

    func book(_ name: String) throws -> KJVBook? {
        lock.lock()
        defer { lock.unlock() }
        if let book = books[name] { return book }
        guard let entry = index.books.first(where: { $0.book == name }) else { return nil }
        let book = try JSONDecoder().decode(KJVBook.self, from: Data(contentsOf: directory.appendingPathComponent(entry.path)))
        books[name] = book
        return book
    }

    public func passage(_ reference: ScriptureReference) throws -> ScripturePassage? {
        guard let book = try book(reference.book) else { return nil }
        let endChapter = reference.endChapter ?? reference.startChapter
        guard reference.startChapter <= endChapter else { return nil }
        var chapters: [KJVBook.Chapter] = []
        for n in reference.startChapter...endChapter {
            guard let chapter = book.chapters.first(where: { $0.chapter == n }) else { return nil }
            chapters.append(chapter)
        }
        let first = VerseLocation(chapter: reference.startChapter, verse: reference.startVerse ?? 1)
        let last = VerseLocation(chapter: endChapter, verse: reference.endVerse ?? chapters.last!.verseCount)
        guard first <= last, last.verse <= chapters.last!.verseCount else { return nil }

        var verses: [ScriptureVerse] = []
        var missing: [VerseLocation] = []
        var lines: [Int] = []
        var pages: Set<Int> = []
        for chapter in chapters {
            for verse in chapter.verses {
                let at = VerseLocation(chapter: chapter.chapter, verse: verse.verse)
                guard first <= at, at <= last else { continue }
                verses.append(ScriptureVerse(chapter: chapter.chapter, number: verse.verse,
                                             segments: verse.segments, review: verse.review))
                lines += verse.lines
                pages.formUnion(verse.pages)
            }
            missing += chapter.missing.map { VerseLocation(chapter: chapter.chapter, verse: $0) }.filter { first <= $0 && $0 <= last }
        }
        let source = lines.isEmpty ? nil
            : SourceReference(sourceID: sourceID, rawLines: lines.min()!...lines.max()!, pages: pages.sorted())
        return ScripturePassage(reference: reference, translationID: translationID, verses: verses,
                                missing: missing.sorted(), source: source)
    }
}

/// The books the bundled text contains.
public struct KJVIndex: Hashable, Sendable, Codable {
    public struct Entry: Hashable, Sendable, Codable {
        public var book: String
        public var path: String
        public var chapters: Int
    }

    public var schemaVersion: Int
    public var books: [Entry]
}

/// One book of the bundled text, as generated by Tools/ContentExtraction.
struct KJVBook: Hashable, Sendable, Codable {
    struct Verse: Hashable, Sendable, Codable {
        var verse: Int
        var segments: [ScriptureVerse.Segment]
        /// First and last line of the transcription (`Provenance/transcription.txt`).
        var lines: [Int]
        /// PDF pages of the witness.
        var pages: [Int]
        var review: String?

        enum CodingKeys: String, CodingKey { case verse, segments, lines, pages, review }

        /// Segments are written as plain strings, and supplied words as
        /// `{"supplied": "…"}`.
        private struct Supplied: Codable { var supplied: String }

        init(from decoder: Decoder) throws {
            let c = try decoder.container(keyedBy: CodingKeys.self)
            verse = try c.decode(Int.self, forKey: .verse)
            lines = try c.decode([Int].self, forKey: .lines)
            pages = try c.decode([Int].self, forKey: .pages)
            review = try c.decodeIfPresent(String.self, forKey: .review)
            var list = try c.nestedUnkeyedContainer(forKey: .segments)
            var segments: [ScriptureVerse.Segment] = []
            while !list.isAtEnd {
                if let text = try? list.decode(String.self) {
                    segments.append(.init(text))
                } else {
                    segments.append(.init(try list.decode(Supplied.self).supplied, supplied: true))
                }
            }
            self.segments = segments
        }

        func encode(to encoder: Encoder) throws {
            var c = encoder.container(keyedBy: CodingKeys.self)
            try c.encode(verse, forKey: .verse)
            try c.encode(lines, forKey: .lines)
            try c.encode(pages, forKey: .pages)
            try c.encodeIfPresent(review, forKey: .review)
            var list = c.nestedUnkeyedContainer(forKey: .segments)
            for segment in segments {
                if segment.supplied { try list.encode(Supplied(supplied: segment.text)) } else { try list.encode(segment.text) }
            }
        }
    }

    struct Chapter: Hashable, Sendable, Codable {
        var chapter: Int
        /// The number of verses the chapter has in the King James Version.
        var verseCount: Int
        var verses: [Verse]
        /// Verses of the chapter the source lacks.
        var missing: [Int]
    }

    var schemaVersion: Int
    var book: String
    var chapters: [Chapter]
}
